create table if not exists public.ordenes_retiro (
    id bigint generated by default as identity primary key,
    numero_orden text not null unique,
    anio integer not null,
    numero_anual bigint not null,
    chofer_id bigint not null references public.choferes(id),
    recibido_de text not null,
    cuit_transportista text not null,
    importe_recibido numeric(14, 2) not null check (importe_recibido > 0),
    total numeric(14, 2) not null check (total > 0),
    observacion text not null,
    created_at timestamptz not null default now(),
    unique (anio, numero_anual)
);

update public.ordenes_retiro
set numero_orden = 'R ' || (anio - 2025)::text || ' ' || numero_anual::text
where numero_orden !~ '^R [0-9]+ [0-9]+$';

