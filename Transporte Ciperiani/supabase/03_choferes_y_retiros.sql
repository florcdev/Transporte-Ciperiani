create or replace function public.crear_orden_retiro(
    p_chofer_id bigint,
    p_recibido_de text,
    p_cuit_transportista text,
    p_importe_recibido numeric,
    p_total numeric,
    p_observacion text
)
returns setof public.ordenes_retiro
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_anio integer := extract(year from (now() at time zone 'America/Argentina/Buenos_Aires'))::integer;
    v_numero_anual bigint;
begin
    if not exists (
        select 1 from public.perfiles_acceso p
        where p.user_id = (select auth.uid()) and p.aprobado
    ) then
        raise exception 'La cuenta no está aprobada para generar órdenes de retiro.';
    end if;

    if p_chofer_id is null or nullif(trim(p_recibido_de), '') is null
       or nullif(trim(p_cuit_transportista), '') is null
       or p_importe_recibido is null or p_importe_recibido <= 0
       or p_total is null or p_total <= 0
       or nullif(trim(p_observacion), '') is null then
        raise exception 'Completá todos los datos de la orden e ingresá importes mayores a cero.';
    end if;

    insert into public.contadores_orden_retiro (anio, ultimo_numero)
    values (v_anio, 1)
    on conflict (anio) do update
    set ultimo_numero = contadores_orden_retiro.ultimo_numero + 1
    returning ultimo_numero into v_numero_anual;

    return query
    insert into public.ordenes_retiro (
        numero_orden, anio, numero_anual, chofer_id, recibido_de,
        cuit_transportista, importe_recibido, total, observacion
    )
    values (
        'R ' || (v_anio - 2025)::text || ' ' || v_numero_anual::text,
        v_anio, v_numero_anual, p_chofer_id, trim(p_recibido_de),
        trim(p_cuit_transportista), p_importe_recibido, p_total, trim(p_observacion)
    )
    returning *;
end;
$$;

revoke all on function public.crear_orden_retiro(bigint, text, text, numeric, numeric, text) from public, anon;
grant execute on function public.crear_orden_retiro(bigint, text, text, numeric, numeric, text) to authenticated;

create or replace function public.registrar_pago_chofer(
    p_chofer_id bigint,
    p_importe numeric
)
returns setof public.pagos_choferes
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_generado numeric(14, 2);
    v_retiros numeric(14, 2);
    v_pagos numeric(14, 2);
    v_disponible numeric(14, 2);
begin
    if not exists (
        select 1 from public.perfiles_acceso p
        where p.user_id = (select auth.uid()) and p.aprobado
    ) then
        raise exception 'La cuenta no está aprobada para registrar pagos.';
    end if;

    if p_chofer_id is null or p_importe is null or p_importe <= 0 then
        raise exception 'Seleccioná un chofer e ingresá un importe mayor a cero.';
    end if;

    perform pg_catalog.pg_advisory_xact_lock(p_chofer_id);

    select coalesce(sum(
        round(
            round(
                round(
                    round(v.toneladas * v.tarifa, 2)
                    - round(round(v.toneladas * v.tarifa, 2) * v.comision_porcentaje / 100, 2),
                    2
                ) * 0.15,
                2
            )
            - v.adelanto
            + coalesce((
                select sum((gasto ->> 'monto')::numeric)
                from jsonb_array_elements(coalesce(v.gastos_extra, '[]'::jsonb)) gasto
                where gasto ->> 'destino' = 'chofer'
            ), 0),
            2
        )
    ), 0)
    into v_generado
    from public.viajes v
    where v.chofer_id = p_chofer_id;

    select coalesce(sum(o.total), 0)
    into v_retiros
    from public.ordenes_retiro o
    where o.chofer_id = p_chofer_id;

    select coalesce(sum(p.importe), 0)
    into v_pagos
    from public.pagos_choferes p
    where p.chofer_id = p_chofer_id;

    v_disponible := v_generado - v_retiros - v_pagos;

    if p_importe > v_disponible then
        raise exception 'El importe supera el saldo disponible del chofer: %.', v_disponible;
    end if;

    return query
    insert into public.pagos_choferes (chofer_id, importe)
    values (p_chofer_id, p_importe)
    returning *;
end;
$$;

revoke all on function public.registrar_pago_chofer(bigint, numeric) from public, anon;
grant execute on function public.registrar_pago_chofer(bigint, numeric) to authenticated;

create or replace function public.crear_orden_pago_cliente(
    p_cliente_id bigint,
    p_detalles jsonb
)
returns setof public.ordenes_pago_clientes
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_anio integer := extract(year from (now() at time zone 'America/Argentina/Buenos_Aires'))::integer;
    v_numero_anual bigint;
    v_total numeric(14, 2) := 0;
    v_generado numeric(14, 2);
    v_pagado numeric(14, 2);
    v_pendiente numeric(14, 2);
    v_detalle jsonb;
    v_importe numeric(14, 2);
begin
    if not exists (
        select 1 from public.perfiles_acceso p
        where p.user_id = (select auth.uid()) and p.aprobado
    ) then
        raise exception 'La cuenta no está aprobada para generar órdenes de pago.';
    end if;

    if p_cliente_id is null or not exists (
        select 1 from public.clientes c where c.id = p_cliente_id and c.activo
    ) then
        raise exception 'Seleccioná un cliente activo.';
    end if;

    if p_detalles is null or jsonb_typeof(p_detalles) <> 'array' then
        raise exception 'La orden debe incluir al menos un detalle de pago.';
    end if;
    if jsonb_array_length(p_detalles) = 0 then
        raise exception 'La orden debe incluir al menos un detalle de pago.';
    end if;

    perform pg_catalog.pg_advisory_xact_lock(p_cliente_id);

    for v_detalle in select value from jsonb_array_elements(p_detalles)
    loop
        if nullif(trim(v_detalle ->> 'concepto'), '') is null
           or v_detalle ->> 'medio' not in ('Cheque', 'Transferencia', 'Efectivo')
           or nullif(v_detalle ->> 'fecha', '') is null
           or nullif(v_detalle ->> 'monto', '') is null
           or (v_detalle ->> 'medio' = 'Transferencia'
               and nullif(trim(v_detalle ->> 'banco'), '') is null) then
            raise exception 'Cada detalle debe tener descripción, medio de pago, fecha, monto y banco para transferencias.';
        end if;

        begin
            v_importe := (v_detalle ->> 'monto')::numeric;
            perform (v_detalle ->> 'fecha')::date;
        exception when invalid_text_representation or datetime_field_overflow then
            raise exception 'La fecha o el monto de un detalle no es válido.';
        end;

        if v_importe <= 0 then
            raise exception 'El importe de cada detalle debe ser mayor a cero.';
        end if;

        v_total := v_total + v_importe;
    end loop;
    v_total := round(v_total, 2);

    select coalesce(sum((gasto ->> 'monto')::numeric), 0)
    into v_generado
    from public.viajes v
    cross join lateral jsonb_array_elements(coalesce(v.gastos_extra, '[]'::jsonb)) gasto
    where gasto ->> 'destino' = 'cliente'
      and gasto ->> 'clienteId' = p_cliente_id::text;

    select coalesce(sum(o.total), 0)
    into v_pagado
    from public.ordenes_pago_clientes o
    where o.cliente_id = p_cliente_id;

    v_pendiente := round(v_generado - v_pagado, 2);
    if v_total > v_pendiente then
        raise exception 'El total supera el importe pendiente del cliente: %.', v_pendiente;
    end if;

    insert into public.contadores_orden_pago_cliente (anio, ultimo_numero)
    values (v_anio, 1)
    on conflict (anio) do update
    set ultimo_numero = contadores_orden_pago_cliente.ultimo_numero + 1
    returning ultimo_numero into v_numero_anual;

    return query
    insert into public.ordenes_pago_clientes (
        numero_orden, anio, numero_anual, cliente_id, total, detalles
    )
    values (
        'P ' || (v_anio - 2025)::text || ' ' || v_numero_anual::text,
        v_anio, v_numero_anual, p_cliente_id, v_total, p_detalles
    )
    returning *;
end;
$$;

revoke all on function public.crear_orden_pago_cliente(bigint, jsonb) from public, anon;
grant execute on function public.crear_orden_pago_cliente(bigint, jsonb) to authenticated;

