create table if not exists public.recibos_efectivo (
    id bigint generated by default as identity primary key,
    anio integer not null,
    numero_anual bigint not null,
    cliente_id bigint not null references public.clientes(id),
    para text not null,
    metodo_pago text not null check (metodo_pago in ('Efectivo', 'Transferencia', 'Cheque')),
    numero_cheque text,
    importe numeric(14, 2) not null check (importe > 0),
    created_at timestamptz not null default now(),
    unique (anio, numero_anual),
    check (
        (metodo_pago = 'Cheque' and nullif(trim(numero_cheque), '') is not null)
        or (metodo_pago <> 'Cheque' and numero_cheque is null)
    )
);

create table if not exists public.contadores_recibo_efectivo (
    anio integer primary key,
    ultimo_numero bigint not null
);

alter table public.recibos_efectivo enable row level security;
revoke all on public.recibos_efectivo from public, anon, authenticated;
revoke all on public.contadores_recibo_efectivo from public, anon, authenticated;
grant select on public.recibos_efectivo to authenticated;

do $$
declare
    v_politica record;
    v_secuencia text := pg_get_serial_sequence('public.recibos_efectivo', 'id');
begin
    for v_politica in
        select policyname
        from pg_policies
        where schemaname = 'public'
          and tablename = 'recibos_efectivo'
    loop
        execute format('drop policy %I on public.recibos_efectivo', v_politica.policyname);
    end loop;

    if v_secuencia is not null then
        execute format('revoke all on sequence %s from public, anon, authenticated', v_secuencia);
    end if;
end;
$$;

create policy "solo_aprobados_recibos_efectivo"
    on public.recibos_efectivo
    for select to authenticated
    using (
        exists (
            select 1 from public.perfiles_acceso p
            where p.user_id = (select auth.uid()) and p.aprobado
        )
    );

create or replace function public.crear_recibo_efectivo(
    p_cliente_id bigint,
    p_para text,
    p_metodo_pago text,
    p_numero_cheque text,
    p_importe numeric
)
returns setof public.recibos_efectivo
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_anio integer := extract(year from (now() at time zone 'America/Argentina/Buenos_Aires'))::integer;
    v_numero_anual bigint;
    v_numero_cheque text;
begin
    if not exists (
        select 1 from public.perfiles_acceso p
        where p.user_id = (select auth.uid()) and p.aprobado
    ) then
        raise exception 'La cuenta no está aprobada para generar recibos de efectivo.';
    end if;

    if p_cliente_id is null or not exists (
        select 1 from public.clientes c where c.id = p_cliente_id and c.activo
    ) then
        raise exception 'Seleccioná un cliente activo.';
    end if;

    if nullif(trim(p_para), '') is null
       or p_metodo_pago is null
       or p_metodo_pago not in ('Efectivo', 'Transferencia', 'Cheque')
       or p_importe is null or p_importe <= 0
       or (p_metodo_pago = 'Cheque' and nullif(trim(p_numero_cheque), '') is null) then
        raise exception 'Completá todos los datos del recibo e ingresá un importe mayor a cero.';
    end if;

    v_numero_cheque := case
        when p_metodo_pago = 'Cheque' then trim(p_numero_cheque)
        else null
    end;

    insert into public.contadores_recibo_efectivo (anio, ultimo_numero)
    values (v_anio, 1)
    on conflict (anio) do update
    set ultimo_numero = contadores_recibo_efectivo.ultimo_numero + 1
    returning ultimo_numero into v_numero_anual;

    return query
    insert into public.recibos_efectivo (
        anio, numero_anual, cliente_id, para, metodo_pago, numero_cheque, importe
    )
    values (
        v_anio, v_numero_anual, p_cliente_id, trim(p_para),
        p_metodo_pago, v_numero_cheque, p_importe
    )
    returning *;
end;
$$;

revoke all on function public.crear_recibo_efectivo(bigint, text, text, text, numeric) from public, anon, authenticated;
grant execute on function public.crear_recibo_efectivo(bigint, text, text, text, numeric) to authenticated;

notify pgrst, 'reload schema';
